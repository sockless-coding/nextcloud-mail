#!/usr/bin/env node
// Translations, in the layout of Nextcloud's translation tooling (translationtool and the
// Transifex bot), without needing PHP or gettext:
//
//   node tools/l10n.mjs extract   write translationfiles/templates/sockless_mail.pot from the frontend
//   node tools/l10n.mjs update    merge the template into translationfiles/<lang>/sockless_mail.po
//   node tools/l10n.mjs compile   write l10n/<lang>.json and l10n/<lang>.js from the .po files
//   node tools/l10n.mjs check     fail if the template is out of date or a translation is broken
//
// Strings are t('sockless_mail', '...') and n('sockless_mail', '...', '...', count) calls with
// literal single- or double-quoted strings in the frontend, and L.T("...") calls with a literal
// string in the backend (src/SocklessMail.Api/Localization/L.cs). Nextcloud's translationtool
// does not read C#, so extract also writes the backend's messages as t() calls into
// src/SocklessMail.Api/Localization/server-strings.js, which it does read. The Transifex bot
// regenerates the template and the l10n/ files itself; these commands produce the same files
// for work without it.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const APP = 'sockless_mail'
const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const frontend = join(root, 'src', 'frontend', 'src')
const backend = join(root, 'src', 'SocklessMail.Api')
const shimPath = join(backend, 'Localization', 'server-strings.js')
const potPath = join(root, 'translationfiles', 'templates', `${APP}.pot`)
const poDir = join(root, 'translationfiles')
const outDir = join(root, 'l10n')

// --- Extraction --------------------------------------------------------------------------

const literal = String.raw`'(?:[^'\\]|\\.)*'|"(?:[^"\\]|\\.)*"`
const callPattern = new RegExp(String.raw`(?<![\w$.])(t|n)\(\s*['"]${APP}['"]\s*,\s*(${literal})(?:\s*,\s*(${literal}))?`, 'g')
const serverPattern = /(?<![\w$.])L\.T\(\s*("(?:[^"\\]|\\.)*")/g

function unquote(token) {
	return token.slice(1, -1).replace(/\\(u[0-9a-fA-F]{4}|x[0-9a-fA-F]{2}|.)/g, (_, e) => {
		switch (e[0]) {
		case 'n': return '\n'
		case 't': return '\t'
		case 'u': case 'x': return String.fromCharCode(parseInt(e.slice(1), 16))
		default: return e
		}
	})
}

function walk(dir, pattern = /\.(js|mjs|vue|ts)$/) {
	return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
		const path = join(dir, entry.name)
		if (entry.isDirectory()) {
			return ['node_modules', 'bin', 'obj', 'wwwroot'].includes(entry.name) ? [] : walk(path, pattern)
		}
		return pattern.test(entry.name) ? [path] : []
	}).sort()
}

/** The backend's messages, in order of first use: id → refs. */
function extractServer() {
	const messages = new Map()
	// Localization/ holds L.cs itself, whose documentation shows an example call.
	for (const file of walk(backend, /\.cs$/).filter((f) => !relative(backend, f).startsWith('Localization'))) {
		const text = readFileSync(file, 'utf8')
		const ref = relative(root, file).replaceAll('\\', '/')
		for (const match of text.matchAll(serverPattern)) {
			const id = unquote(match[1])
			const line = text.slice(0, match.index).split('\n').length
			if (!messages.has(id)) {
				messages.set(id, [])
			}
			messages.get(id).push(`${ref}:${line}`)
		}
	}
	return messages
}

/** server-strings.js: the backend's messages as t() calls, for translationtool. */
function serverShim() {
	const lines = [...extractServer().keys()].map((id) => `t('${APP}', ${JSON.stringify(id)})`)
	return [
		'// Generated by tools/l10n.mjs extract from the L.T("...") calls in the backend; do not edit.',
		'// Nextcloud\'s translationtool does not read C#: this file lists the messages for it. Not loaded anywhere.',
		'/* eslint-disable */',
		...lines,
		'',
	].join('\n')
}

/** Name, summary and description of appinfo/info.xml, which translationtool also extracts. */
function appInfoStrings() {
	const xml = readFileSync(join(root, 'appinfo', 'info.xml'), 'utf8')
	return ['name', 'summary', 'description'].map((tag) => {
		const m = xml.match(new RegExp(`<${tag}>(?:<!\\[CDATA\\[([\\s\\S]*?)\\]\\]>|([^<]*))</${tag}>`))
		return m ? (m[1] ?? m[2]).replace(/\r\n/g, '\n').trim() : null
	}).filter(Boolean)
}

/** Messages in order of first use: key → { id, plural, refs }. */
function extract() {
	const messages = new Map()
	for (const id of appInfoStrings()) {
		messages.set(id, { id, plural: null, refs: ['appinfo/info.xml'] })
	}
	for (const file of walk(frontend)) {
		const text = readFileSync(file, 'utf8')
		const ref = relative(root, file).replaceAll('\\', '/')
		for (const match of text.matchAll(callPattern)) {
			const [, fn, first, second] = match
			const id = unquote(first)
			const plural = fn === 'n' ? (second ? unquote(second) : null) : null
			if (fn === 'n' && plural === null) {
				throw new Error(`${ref}: n() without a literal plural form`)
			}
			const key = plural === null ? id : `${id}\u0004${plural}`
			const line = text.slice(0, match.index).split('\n').length
			if (!messages.has(key)) {
				messages.set(key, { id, plural, refs: [] })
			}
			messages.get(key).refs.push(`${ref}:${line}`)
		}
	}
	for (const [id, refs] of extractServer()) {
		if (!messages.has(id)) {
			messages.set(id, { id, plural: null, refs: [] })
		}
		messages.get(id).refs.push(...refs)
	}
	return messages
}

// --- PO files ----------------------------------------------------------------------------

function poString(value) {
	const escaped = value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\t/g, '\\t')
	const lines = escaped.split('\n')
	if (lines.length === 1) {
		return `"${escaped}"`
	}
	return '""\n' + lines.map((l, i) => `"${l}${i < lines.length - 1 ? '\\n' : ''}"`).filter((l) => l !== '""').join('\n')
}

function writePo(path, header, entries) {
	const out = [header.trimEnd(), '']
	for (const e of entries) {
		for (const ref of e.refs ?? []) {
			out.push(`#: ${ref}`)
		}
		if (e.fuzzy) {
			out.push('#, fuzzy')
		}
		out.push(`msgid ${poString(e.id)}`)
		if (e.plural !== null) {
			out.push(`msgid_plural ${poString(e.plural)}`)
			const forms = e.strs?.length ? e.strs : ['', '']
			forms.forEach((s, i) => out.push(`msgstr[${i}] ${poString(s)}`))
		} else {
			out.push(`msgstr ${poString(e.str ?? '')}`)
		}
		out.push('')
	}
	mkdirSync(dirname(path), { recursive: true })
	writeFileSync(path, out.join('\n'))
}

function potHeader() {
	return [
		'# Sockless Mail translation template. Generated by tools/l10n.mjs extract; do not edit.',
		'msgid ""',
		'msgstr ""',
		'"Project-Id-Version: Sockless Mail\\n"',
		'"Report-Msgid-Bugs-To: https://github.com/sockless-coding/nextcloud-mail/issues\\n"',
		'"MIME-Version: 1.0\\n"',
		'"Content-Type: text/plain; charset=UTF-8\\n"',
		'"Content-Transfer-Encoding: 8bit\\n"',
	].join('\n')
}

/** Parses a .po file into { header (raw text), headers (map), entries }. */
function readPo(path) {
	const text = readFileSync(path, 'utf8').replace(/\r\n/g, '\n')
	const blocks = text.split(/\n{2,}/)
	const entries = []
	let header = ''
	const headers = {}
	for (const block of blocks) {
		if (!block.trim()) {
			continue
		}
		const entry = { refs: [], fuzzy: false, id: null, plural: null, str: null, strs: [] }
		let field = null
		let obsolete = false
		for (const raw of block.split('\n')) {
			const line = raw.trim()
			if (line.startsWith('#~')) {
				obsolete = true
				continue
			}
			if (line.startsWith('#:')) {
				entry.refs.push(...line.slice(2).trim().split(/\s+/))
				continue
			}
			if (line.startsWith('#,')) {
				entry.fuzzy ||= line.includes('fuzzy')
				continue
			}
			if (line.startsWith('#') || !line) {
				continue
			}
			const m = line.match(/^(msgid|msgid_plural|msgstr(?:\[(\d+)\])?)\s+(".*")$/)
			const value = m ? m[3] : line
			if (m) {
				field = m[2] !== undefined ? ['strs', Number(m[2])] : [m[1]]
			}
			// PO escapes (\" \\ \n \t) are a subset of JSON's.
			const piece = JSON.parse(value)
			const [name, index] = field
			const prop = { msgid: 'id', msgid_plural: 'plural', msgstr: 'str', strs: 'strs' }[name]
			if (prop === 'strs') {
				entry.strs[index] = (entry.strs[index] ?? '') + piece
			} else {
				entry[prop] = (entry[prop] ?? '') + piece
			}
		}
		if (obsolete || entry.id === null) {
			continue
		}
		if (entry.id === '') {
			header = block
			for (const h of (entry.str ?? '').split('\n')) {
				const i = h.indexOf(':')
				if (i > 0) {
					headers[h.slice(0, i).trim()] = h.slice(i + 1).trim()
				}
			}
			continue
		}
		entries.push(entry)
	}
	return { header, headers, entries }
}

const keyOf = (e) => e.plural === null ? e.id : `${e.id}\u0004${e.plural}`

function languages() {
	if (!existsSync(poDir)) {
		return []
	}
	return readdirSync(poDir, { withFileTypes: true })
		.filter((d) => d.isDirectory() && d.name !== 'templates' && existsSync(join(poDir, d.name, `${APP}.po`)))
		.map((d) => d.name)
		.sort()
}

// --- Commands ----------------------------------------------------------------------------

function potEntries() {
	return [...extract().values()].map((m) => ({ ...m, str: '', strs: [] }))
}

function cmdExtract() {
	const entries = potEntries()
	writePo(potPath, potHeader(), entries)
	writeFileSync(shimPath, serverShim())
	console.log(`translationfiles/templates/${APP}.pot: ${entries.length} messages (${extractServer().size} from the backend)`)
}

function cmdUpdate() {
	const template = potEntries()
	for (const lang of languages()) {
		const path = join(poDir, lang, `${APP}.po`)
		const po = readPo(path)
		const old = new Map(po.entries.map((e) => [keyOf(e), e]))
		const merged = template.map((t) => {
			const prev = old.get(keyOf(t))
			return prev ? { ...t, str: prev.str, strs: prev.strs, fuzzy: prev.fuzzy } : t
		})
		writePo(path, po.header, merged)
		const done = merged.filter(translated).length
		console.log(`${lang}: ${done}/${merged.length} translated, ${po.entries.length - merged.filter((e) => old.has(keyOf(e))).length} obsolete removed`)
	}
}

function translated(e) {
	return !e.fuzzy && (e.plural === null ? !!e.str : e.strs.length > 0 && e.strs.every((s) => s))
}

const placeholders = (s) => [...s.matchAll(/\{(\w+)\}/g)].map((m) => m[1]).sort().join(',')

/** Problems in a translation: placeholders that differ from the English text. */
function problems(lang, entries) {
	const out = []
	for (const e of entries.filter(translated)) {
		const wanted = placeholders(e.plural === null ? e.id : e.plural)
		const wantedSingular = placeholders(e.id)
		const forms = e.plural === null ? [e.str] : e.strs
		for (const f of forms) {
			const got = placeholders(f)
			// A singular form may drop the count ({count} → "one"), like the English singular.
			if (got !== wanted && got !== wantedSingular) {
				out.push(`${lang}: placeholders {${got}} instead of {${wanted}} in "${e.id}"`)
			}
		}
	}
	return out
}

function cmdCompile() {
	mkdirSync(outDir, { recursive: true })
	for (const lang of languages()) {
		const po = readPo(join(poDir, lang, `${APP}.po`))
		const translations = {}
		for (const e of po.entries.filter(translated)) {
			if (e.plural === null) {
				translations[e.id] = e.str
			} else {
				translations[`_${e.id}_::_${e.plural}_`] = e.strs
			}
		}
		const pluralForm = po.headers['Plural-Forms'] ?? 'nplurals=2; plural=(n != 1);'
		writeFileSync(join(outDir, `${lang}.json`), JSON.stringify({ translations, pluralForm }, null, 4) + '\n')
		writeFileSync(join(outDir, `${lang}.js`),
			`OC.L10N.register(\n    "${APP}",\n    ${JSON.stringify(translations, null, 4).replace(/\n/g, '\n    ')},\n    ${JSON.stringify(pluralForm)});\n`)
		console.log(`l10n/${lang}: ${Object.keys(translations).length} messages`)
	}
}

function cmdCheck() {
	const errors = []
	// The same messages; the Transifex bot's template orders them differently.
	const current = potEntries().map(keyOf).sort().join('\n')
	const committed = existsSync(potPath) ? readPo(potPath).entries.map(keyOf).sort().join('\n') : ''
	if (current !== committed) {
		errors.push(`translationfiles/templates/${APP}.pot is out of date: run node tools/l10n.mjs extract`)
	}
	if (!existsSync(shimPath) || readFileSync(shimPath, 'utf8').replace(/\r\n/g, '\n') !== serverShim()) {
		errors.push('src/SocklessMail.Api/Localization/server-strings.js is out of date: run node tools/l10n.mjs extract')
	}
	for (const lang of languages()) {
		const po = readPo(join(poDir, lang, `${APP}.po`))
		errors.push(...problems(lang, po.entries))
		const json = join(outDir, `${lang}.json`)
		const count = po.entries.filter(translated).length
		if (!existsSync(json) || Object.keys(JSON.parse(readFileSync(json, 'utf8')).translations).length !== count) {
			errors.push(`l10n/${lang}.json does not match its .po file: run node tools/l10n.mjs compile`)
		}
	}
	if (errors.length) {
		console.error(errors.join('\n'))
		process.exit(1)
	}
	console.log(`Translations: template up to date, ${languages().length} language(s) consistent.`)
}

const commands = { extract: cmdExtract, update: cmdUpdate, compile: cmdCompile, check: cmdCheck }
const command = commands[process.argv[2]]
if (!command) {
	console.error('Usage: node tools/l10n.mjs extract|update|compile|check')
	process.exit(1)
}
command()
