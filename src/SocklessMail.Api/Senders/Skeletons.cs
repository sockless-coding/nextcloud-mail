using System.Globalization;
using System.Text;

namespace SocklessMail.Api.Senders;

/// <summary>The writing systems that matter for spotting look-alike domains; everything else is <see cref="Other"/>.</summary>
public enum Script
{
    Common,
    Latin,
    Greek,
    Cyrillic,
    Armenian,
    Cherokee,
    Other,
}

/// <summary>
/// The "skeleton" of a string (UTS #39): what it looks like, with confusable characters replaced by
/// one prototype each, so "pаypal" (Cyrillic а), "paypa1" and "paypal" share a skeleton. Built from
/// Unicode's confusables.txt and canonical decompositions (Senders/Data, regenerated by
/// dev/unicode-data.sh): the app runs with invariant globalization, where string.Normalize does not
/// decompose. Unlike UTS #39, combining marks are dropped, so "páypal" counts as "paypal" too, and the
/// result is lower case, as domain names are.
/// </summary>
public static class Skeletons
{
    private static readonly Dictionary<int, int[]> Decompositions = Load("decompositions.txt");
    private static readonly Dictionary<int, int[]> Confusables = Load("confusables.txt");

    /// <summary>
    /// Look-alikes in plain ASCII that confusables.txt leaves out (it has rn for m, 1 and I for l, 0
    /// for O). Applied after lower-casing, so "vv" and "w", "cl" and "d" end up the same.
    /// </summary>
    private static readonly (string From, string To)[] AsciiLookalikes = [("w", "vv"), ("d", "cl")];

    public static string Of(string text)
    {
        var mapped = new StringBuilder(text.Length);
        foreach (var rune in text.ToLowerInvariant().EnumerateRunes())
        {
            foreach (var decomposed in Decompose(rune.Value))
            {
                if (Confusables.TryGetValue(decomposed, out var prototype))
                {
                    foreach (var part in prototype.SelectMany(Decompose))
                    {
                        Append(mapped, part);
                    }
                }
                else
                {
                    Append(mapped, decomposed);
                }
            }
        }

        var skeleton = mapped.ToString().ToLowerInvariant();
        foreach (var (from, to) in AsciiLookalikes)
        {
            skeleton = skeleton.Replace(from, to, StringComparison.Ordinal);
        }

        return skeleton;
    }

    /// <summary>Whether <paramref name="text"/> mixes alphabets that are confusable with each other, such as Latin and Cyrillic.</summary>
    public static bool MixesScripts(string text)
    {
        var scripts = text.EnumerateRunes().Select(r => ScriptOf(r.Value)).Where(s => s is not (Script.Common or Script.Other)).Distinct().Count();
        return scripts > 1;
    }

    public static Script ScriptOf(int c) => c switch
    {
        < 0x80 => char.IsAsciiLetter((char)c) ? Script.Latin : Script.Common,
        (>= 0xC0 and <= 0x24F) and not (0xD7 or 0xF7) => Script.Latin,
        >= 0x1E00 and <= 0x1EFF => Script.Latin,
        >= 0x2C60 and <= 0x2C7F => Script.Latin,
        >= 0xA720 and <= 0xA7FF => Script.Latin,
        >= 0xFF21 and <= 0xFF3A or >= 0xFF41 and <= 0xFF5A => Script.Latin,
        >= 0x370 and <= 0x3FF => Script.Greek,
        >= 0x1F00 and <= 0x1FFF => Script.Greek,
        >= 0x400 and <= 0x52F => Script.Cyrillic,
        >= 0x1C80 and <= 0x1C8F => Script.Cyrillic,
        >= 0x2DE0 and <= 0x2DFF => Script.Cyrillic,
        >= 0xA640 and <= 0xA69F => Script.Cyrillic,
        >= 0x530 and <= 0x58F => Script.Armenian,
        >= 0x13A0 and <= 0x13FF or >= 0xAB70 and <= 0xABBF => Script.Cherokee,
        _ when CharUnicodeInfo.GetUnicodeCategory(c) is UnicodeCategory.NonSpacingMark or UnicodeCategory.DecimalDigitNumber
            or UnicodeCategory.DashPunctuation => Script.Common,
        _ => Script.Other,
    };

    private static IEnumerable<int> Decompose(int c) =>
        Decompositions.TryGetValue(c, out var parts) ? parts.SelectMany(Decompose) : [c];

    private static void Append(StringBuilder builder, int c)
    {
        if (CharUnicodeInfo.GetUnicodeCategory(c) != UnicodeCategory.NonSpacingMark)
        {
            builder.Append(char.ConvertFromUtf32(c));
        }
    }

    /// <summary>"XXXX;YYYY ZZZZ" lines (hex code points); '#' starts a comment line.</summary>
    private static Dictionary<int, int[]> Load(string name)
    {
        using var stream = typeof(Skeletons).Assembly.GetManifestResourceStream($"SocklessMail.Api.Senders.Data.{name}")
                           ?? throw new InvalidOperationException($"The embedded resource {name} is missing.");
        using var reader = new StreamReader(stream);
        var table = new Dictionary<int, int[]>();
        while (reader.ReadLine() is { } line)
        {
            if (line.Length == 0 || line[0] == '#' || line.Split(';') is not [var source, var target])
            {
                continue;
            }

            table[int.Parse(source, NumberStyles.HexNumber, CultureInfo.InvariantCulture)] = target
                .Split(' ', StringSplitOptions.RemoveEmptyEntries)
                .Select(hex => int.Parse(hex, NumberStyles.HexNumber, CultureInfo.InvariantCulture))
                .ToArray();
        }

        return table;
    }
}
